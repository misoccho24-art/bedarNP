# Beda News - deploy builder.   Run:  powershell -ExecutionPolicy Bypass -File .\build.ps1
# LOCAL ONLY - never upload this file.
#
# Your working files are NOT changed. Everything happens in a temporary copy, and the
# result is deploy.zip: upload it to public_html and Extract.
#
# 1. core = data.js + geo.js + store.js + main.js (one request instead of four).
# 2. css/style.css (comments stripped) goes into a <style> inside every page, so the
#    first paint does not wait for a separate CSS download.
# 3. Every script gets a NEW FILE NAME containing a hash of everything that ships,
#    e.g. js/core.ab3800c6.js. A new name can never be served stale from a browser
#    cache, and never collides with an old file on the server.
# 4. deploy.zip never contains posts.json, token/attempt files or uploaded photos,
#    so extracting it cannot touch the news. It does include data/.htaccess (keeps
#    the data folder private) and the empty-folder READMEs.
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)
function Read-Utf8($rel) { [System.IO.File]::ReadAllText((Join-Path $root $rel), $utf8) }

# ---- sources ----
$coreParts = 'data', 'geo', 'store', 'main'
$core = "/* GENERATED by build.ps1 from data.js + geo.js + store.js + main.js - edit those, not this file */`n" +
        (($coreParts | ForEach-Object { Read-Utf8 "js\$_.js" }) -join "`n;`n")
$pageScripts = @{}
foreach ($n in 'home', 'category', 'article', 'admin', 'page') { $pageScripts[$n] = Read-Utf8 "js\$n.js" }

$css = Read-Utf8 'css\style.css'
$css = [regex]::Replace($css, '(?s)/\*.*?\*/', '')
$css = (($css -split "`r?`n" | ForEach-Object { $_.Trim() } | Where-Object { $_ -ne '' }) -join "`n")

# ---- version = hash of everything that ships ----
$all = $core + $css + (($pageScripts.Keys | Sort-Object | ForEach-Object { $pageScripts[$_] }) -join '')
$ver = -join ([System.Security.Cryptography.SHA1]::Create().ComputeHash($utf8.GetBytes($all))[0..3] | ForEach-Object { $_.ToString('x2') })

# ---- stage ----
$stage = Join-Path ([System.IO.Path]::GetTempPath()) ('beda-deploy-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Force (Join-Path $stage 'js') | Out-Null
function Write-Stage($rel, $text) {
  $dst = Join-Path $stage $rel
  New-Item -ItemType Directory -Force (Split-Path $dst) | Out-Null
  [System.IO.File]::WriteAllText($dst, $text, $utf8)
}

Write-Stage "js\core.$ver.js" $core
foreach ($n in $pageScripts.Keys) { Write-Stage "js\$n.$ver.js" $pageScripts[$n] }

# ---- pages: inline CSS, one core script, hashed page script ----
$shells = 'index.html', 'category.html', 'article.html', 'admin71.html', 'about.html', 'contact.html',
          'privacy.html', 'terms.html', 'advertise.html', 'article-og.php'
foreach ($f in $shells) {
  $t = Read-Utf8 $f
  $t = [regex]::Replace($t, '<link rel="stylesheet" href="css/style\.css(?:\?v=[0-9A-Za-z]+)?">',
         { param($m) "<style>`n" + $css + "`n</style>" })
  $t = [regex]::Replace($t, '<script src="js/data\.js(?:\?v=[0-9A-Za-z]+)?"></script>',
         { param($m) '<script src="js/core.' + $ver + '.js"></script>' })
  $t = [regex]::Replace($t, '<script src="js/(?:geo|store|main)\.js(?:\?v=[0-9A-Za-z]+)?"></script>\r?\n?', '')
  $t = [regex]::Replace($t, 'js/(home|category|article|admin|page)\.js(?:\?v=[0-9A-Za-z]+)?',
         { param($m) 'js/' + $m.Groups[1].Value + '.' + $ver + '.js' })
  if ($t -match 'css/style\.css|js/(data|geo|store|main)\.js') { throw "$f still points at an unbuilt file - check its <link>/<script> tags" }
  Write-Stage $f $t
}

# ---- other files that belong on the server ----
$copy = '.htaccess', 'admin\index.html', 'api\posts.php', 'data\.htaccess', 'data\README.txt', 'uploads\README.txt'
foreach ($f in $copy) {
  $src = Join-Path $root $f
  if (Test-Path $src) {
    $dst = Join-Path $stage $f
    New-Item -ItemType Directory -Force (Split-Path $dst) | Out-Null
    Copy-Item $src $dst
  }
}

# ---- deploy.zip ----
$zip = Join-Path $root 'deploy.zip'
if (Test-Path $zip) { Remove-Item $zip }
# Windows' own bsdtar (not Git's tar, which misreads C:\ paths); it writes forward-slash
# paths, which Compress-Archive on PS 5.1 does not
$tar = Join-Path $env:SystemRoot 'System32\tar.exe'
& $tar -a -c -f $zip -C $stage .
$tarExit = $LASTEXITCODE
Remove-Item -Recurse -Force $stage
if ($tarExit -ne 0 -or -not (Test-Path $zip)) { throw "making deploy.zip failed (tar exit $tarExit)" }

"built v=$ver  core=$([int]($core.Length/1024))KB  inline css=$([int]($css.Length/1024))KB  pages=$($shells.Count)"
"deploy.zip ready ($([int]((Get-Item $zip).Length/1024)) KB):"
& $tar -t -f $zip | Where-Object { $_ -notmatch '/$' }
